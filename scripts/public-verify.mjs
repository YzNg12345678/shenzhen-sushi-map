// 公网验收：真实桌面 / 390x844 浏览器访问线上 URL，检查标题、主清单、价位、详情字段、图鉴、真实高德地图、核心交互与页面错误。
import { chromium } from "@playwright/test";
import { writeFileSync } from "node:fs";
const URL0 = "https://yzng12345678.github.io/shenzhen-sushi-map/";
const out = { url: URL0, checkedAt: new Date().toISOString(), runs: [] };
const b = await chromium.launch({ args: ["--no-sandbox"] });
for (const [name, vp, mobile] of [["desktop", { width: 1360, height: 900 }, false], ["mobile-390x844", { width: 390, height: 844 }, true]]) {
  const ctx = await b.newContext({ viewport: vp, isMobile: mobile, hasTouch: mobile });
  const p = await ctx.newPage();
  const errs = [];
  p.on("pageerror", (e) => errs.push("pageerror: " + e.message));
  p.on("console", (m) => { if (m.type() === "error") errs.push("console: " + m.text().replace(/\?[^\s]*/g, "?[R]").slice(0, 160)); });
  const r = { name, checks: {} };
  await p.goto(URL0);
  r.checks.title = await p.title();
  await p.getByTestId("pin").first().waitFor({ state: "attached", timeout: 120000 });
  r.checks.count = await p.getByTestId("count").innerText();
  r.checks.pins = await p.getByTestId("pin").count();
  r.checks.amapCanvas = await p.locator(".amap-layer, .amap-maps").count() > 0;
  const prices = await p.getByTestId("card-price").allInnerTexts();
  r.checks.prices = prices.map((t) => t.split("\n")[0]);
  r.checks.allPricesAtLeast300 = prices.every((t) => Number(/¥(\d+)/.exec(t)?.[1]) >= 300);
  r.checks.names = await p.locator("[data-testid=shop-card] h3").allInnerTexts();
  const body = await p.locator("body").innerText();
  r.checks.noOldFramework = !["三件事", "稳不稳", "带父母合不合适", "值不值得专程过关", "三轴"].some((s) => body.includes(s));
  await p.waitForTimeout(2500);
  await p.screenshot({ path: `artifacts/screenshots/public-${name}-01-home.png` });
  await p.getByTestId("shop-card").first().locator("h3 button").click({ timeout: 120000 });
  await p.getByTestId("shop-sheet").waitFor();
  r.checks.detailFields = {};
  for (const k of ["cuisine", "ingredients", "chef", "menu", "value", "space", "booking", "scenes"]) r.checks.detailFields[k] = (await p.getByTestId(`field-${k}`).innerText()).replace(/\s+/g, " ").slice(0, 60);
  r.checks.hasStrengthsRisksConfidence = (await p.getByTestId("strengths").count()) + (await p.getByTestId("risks").count()) + (await p.getByTestId("confidence").count()) === 3;
  r.checks.sourceLinks = await p.getByTestId("shop-sheet").locator("a[href^=http]").count();
  await p.screenshot({ path: `artifacts/screenshots/public-${name}-02-detail.png` });
  await p.keyboard.press("Escape");
  await p.goto(URL0 + "atlas/");
  r.checks.atlasTitle = await p.title();
  r.checks.atlasCount = await p.getByTestId("atlas-count").innerText();
  await p.locator("#aq").fill("鲷");
  r.checks.atlasSearch = await p.getByTestId("atlas-count").innerText();
  await p.screenshot({ path: `artifacts/screenshots/public-${name}-03-atlas.png` });
  await p.getByTestId("atlas-card").first().getByRole("link").click();
  await p.getByTestId("atlas-detail").waitFor();
  r.checks.atlasDetail = (await p.locator("h1").innerText());
  r.checks.seasonNote = (await p.getByTestId("season-note").innerText()).slice(0, 50);
  r.checks.overflow = await p.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
  r.errors = errs.filter((e) => !/amap|webgl|canvas|Failed to load resource/i.test(e));
  r.errorsAll = errs.length;
  out.runs.push(r);
  await ctx.close();
}
await b.close();
writeFileSync("artifacts/report/public-verify.json", JSON.stringify(out, null, 2));
console.log(JSON.stringify(out.runs.map((r) => ({ name: r.name, title: r.checks.title, count: r.checks.count, pins: r.checks.pins, prices: r.checks.prices, ge300: r.checks.allPricesAtLeast300, old: !r.checks.noOldFramework, atlas: r.checks.atlasCount, overflow: r.checks.overflow, errors: r.errors })), null, 1));
